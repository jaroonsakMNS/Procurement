export function computeKpis(
  jobs: VendorJob[],
  orders: PurchaseOrder[],
  payments: PendingPayment[],
  deliveries: PendingDelivery[],
  equipment: JobEquipmentItem[],
  inventory: InventoryItem[] = [],
  pending: PendingPurchaseItem[] = [],
): DashboardKpis {
  return {
    vendorJobsReady: jobs.filter((job) => job.status === 'ready_for_po').length,
    posInProcess: orders.filter((order) => order.stage !== 'delivered').length,
    pendingPaymentTotal: payments.reduce((sum, item) => sum + item.amount, 0),
    pendingDeliveriesCount: deliveries.length,
    orderedEquipmentCount: equipment.filter((item) => item.status === 'ordered').length,
    lowStockCount: inventory.filter((item) => item.currentStock <= item.minStock).length,
    pendingPurchaseCount: pending.filter((item) => item.status === 'pending').length,
  }
}

export const kpis: DashboardKpis = computeKpis(
  vendorJobs,
  purchaseOrders,
  pendingPayments,
  pendingDeliveries,
  jobEquipment,
)
